// Prepares the Windows release payload without external hosting:
// - runtime/python: pinned python-build-standalone portable Python (pip + packaging only)
// - modules/MaiBot/plugins/snowluma-adapter: pinned upstream commit from
//   resources/snowluma-adapter-upstream.json
// Existing valid payloads are kept unless --force is passed. Use --root <dir>
// to target another checkout. On non-Windows hosts only the layout is prepared
// and verified; pip/packaging installation requires Windows.
import { existsSync, mkdirSync, mkdtempSync, renameSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { PACKAGING_VERSION, download, parsePayloadArgs, prepareSnowLumaAdapter, run, sha256 } from "./payload-utils.ts";

const PYTHON_BUILD = {
  release: "20261110",
  version: "3.12.16",
  url: "https://github.com/astral-sh/python-build-standalone/releases/download/20261110/cpython-3.12.16%2B20261110-x86_64-pc-windows-msvc-install_only.tar.gz",
  sha256: "e23fe5b16926de1d81661b1a97352e89fb167549c55a6825796ccd0f32ec7f1b",
};
// PBS bundles this pip version; reinstalling it generates the Scripts/pip.exe
// launchers that the release payload check requires (PBS ships an empty Scripts/).
const PIP_VERSION = "26.3";

function layoutValid(pythonRoot: string): boolean {
  return ["python.exe", "Lib", "DLLs", join("Lib", "site-packages", "pip")]
    .every((entry) => existsSync(join(pythonRoot, entry)));
}

async function preparePython(root: string, force: boolean): Promise<void> {
  const pythonRoot = join(root, "runtime", "python");
  const python = join(pythonRoot, "python.exe");
  const pipExe = join(pythonRoot, "Scripts", "pip.exe");
  const executable = process.platform === "win32";
  if (!force && layoutValid(pythonRoot)) {
    if (!executable) {
      console.log("runtime/python layout already valid, keeping it (execution checks require Windows)");
      return;
    }
    if (existsSync(pipExe)) {
      try {
        run(python, ["-c", "import packaging"]);
        console.log(`runtime/python already valid (${run(python, ["--version"])}), keeping it`);
        return;
      } catch {
        console.log("runtime/python exists but packaging is missing; repairing");
      }
    }
  } else {
    const scratch = mkdtempSync(join(tmpdir(), "maibot-python-"));
    try {
      const archive = join(scratch, "python.tar.gz");
      await download(PYTHON_BUILD.url, archive);
      const actual = sha256(archive);
      if (actual !== PYTHON_BUILD.sha256) {
        throw new Error(`Python payload SHA-256 mismatch. Expected ${PYTHON_BUILD.sha256}, got ${actual}.`);
      }
      run("tar", ["-xzf", archive, "-C", scratch]);
      const extracted = join(scratch, "python");
      if (!layoutValid(extracted)) {
        throw new Error("Python archive layout changed: expected python.exe, Lib, DLLs and site-packages/pip");
      }
      mkdirSync(join(root, "runtime"), { recursive: true });
      rmSync(pythonRoot, { recursive: true, force: true });
      renameSync(extracted, pythonRoot);
    } finally {
      rmSync(scratch, { recursive: true, force: true });
    }
  }
  if (executable) {
    run(python, ["-m", "pip", "install", "--disable-pip-version-check", "--force-reinstall",
      `pip==${PIP_VERSION}`, `packaging==${PACKAGING_VERSION}`]);
    run(python, ["-c", "import packaging"]);
    if (!existsSync(pipExe)) throw new Error("Scripts/pip.exe was not generated by the pip reinstall");
    console.log(`runtime/python ready: ${run(python, ["--version"])}`);
  } else {
    console.log("runtime/python extracted; pip/packaging installation runs on Windows");
  }
}

const { root, force } = parsePayloadArgs(process.argv.slice(2));
await preparePython(root, force);
await prepareSnowLumaAdapter(root, force);
console.log("Windows release payload ready");
